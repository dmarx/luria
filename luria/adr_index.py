from __future__ import annotations
import os.path
import posixpath
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
import yaml
from .config import current
TITLE_RE = re.compile('^#\\s*[A-Z]+-[A-Za-z0-9]+\\s*(?::|—|-)\\s*')
TABLE_HEAD = '| # | Title | Summary | Status |\n|---|---|---|---|\n'
_CELL_PIPE_RE = re.compile('\\\\?\\|')

def escape_cell(text: str) -> str:
    return _CELL_PIPE_RE.sub('\\\\|', text)
DEFAULT_DOCUMENT_STUB = '# {title}\n\n<!-- GENERATED by `luria index` — edit the fragments, not this file. -->\n\n{principles}\n'
DEFAULT_STUB = '# {title}\n\n<!-- GENERATED below this line by `luria index` — edit README.stub instead. -->\n\n{categories}\n\n{table}\n'
RELATIVE_LINK_RE = re.compile('(?<=\\]\\()(?![#/]|[A-Za-z][A-Za-z0-9+.-]*:)([^)\\s]+)')

def rebase_links(text: str, prefix: str) -> str:
    if not prefix:
        return text
    return RELATIVE_LINK_RE.sub(lambda m: _normalize(prefix + m.group(1)), text)

def _normalize(target: str) -> str:
    path, sep, fragment = target.partition('#')
    return (posixpath.normpath(path) if path else path) + sep + fragment

def prefix_for(scheme, out_dir: Path) -> str:
    rel = os.path.relpath(scheme.dir, out_dir)
    return '' if rel == '.' else rel + '/'

def parse_frontmatter(text: str) -> tuple[dict, str]:
    if not text.startswith('---\n'):
        return ({}, text)
    end = text.find('\n---\n', 3)
    if end == -1:
        return ({}, text)
    return (yaml.safe_load(text[4:end + 1]) or {}, text[end + 5:])

class Adr:

    def __init__(self, path: Path, scheme=None):
        scheme = scheme or current().schemes['ADR']
        self.path = path
        self.scheme = scheme
        self.prefix = scheme.prefix
        self.number = scheme.number_of(path)
        self.tail = scheme.temp_of(path)
        self.meta, body = parse_frontmatter(path.read_text())
        first = next((ln for ln in body.splitlines() if ln.startswith('#')), '')
        self.heading = TITLE_RE.sub('', first).strip()
        self.title = str(self.meta.get('title') or '').strip() or self.heading

    @property
    def code(self) -> str:
        if self.number is None and self.tail:
            return f'{self.prefix}-{self.tail}'
        return f'{self.prefix}-{self.number:03d}'

    @property
    def status(self) -> str:
        return str(self.meta.get('status', '')).strip()

    @property
    def tags(self) -> list[str]:
        return [str(t).strip().lower() for t in self.meta.get('tags') or []]

    def cell(self, prefix: str='') -> str:
        return rebase_links(str(self.meta.get('summary') or '').strip(), prefix)

    @property
    def version(self) -> int:
        return int(self.meta.get('version', 1) or 1)

    @property
    def influenced_by(self) -> list[str]:
        raw = self.meta.get('influenced_by') or []
        return [str(x).strip() for x in raw]

    def row(self, prefix: str='') -> str:
        version = f' v{self.version}' if self.version > 1 else ''
        return f'| [{self.code}]({prefix}{self.path.name}){version} | {escape_cell(self.title)} | {escape_cell(self.cell(prefix))} | {escape_cell(rebase_links(self.status, prefix))} |'

def load_adrs() -> list[Adr]:
    return load_scheme(current().schemes['ADR'])

def load_scheme(scheme) -> list[Adr]:
    docs = [Adr(p, scheme) for p in scheme.documents().values()]
    temps = [Adr(p, scheme) for p in scheme.temp_documents().values()]
    temps.sort(key=lambda a: (str(a.meta.get('date', '')), a.path.name))
    return docs + temps

def tag_order(adrs: list[Adr], scheme=None) -> list[tuple[str, dict]]:
    tags_file = scheme.tags_yaml if scheme else current().tags_yaml
    declared = yaml.safe_load(tags_file.read_text()) if tags_file.exists() else {}
    declared = declared or {}
    used = {t for a in adrs for t in a.tags}
    ordered = [(t, declared[t] or {}) for t in declared if t in used]
    ordered += [(t, {}) for t in sorted(used - set(declared))]
    return ordered

def render_categories(adrs: list[Adr], tags: list[tuple[str, dict]], prefix: str='') -> str:
    blocks = []
    for tag, meta in tags:
        listed = [a for a in adrs if tag in a.tags]
        label = meta.get('label', tag.title())
        blurb = f" — {meta['blurb']}" if meta.get('blurb') else ''
        links = ' · '.join((f'[{a.number:03d}]({prefix}{a.path.name})' if a.number is not None else f'[{a.tail}]({prefix}{a.path.name})' for a in listed))
        blocks.append(f'**[{label}](tags/{tag}.md)** ({len(listed)}){blurb}:\n{links}')
    return '\n\n'.join(blocks)

def render_index(adrs: list[Adr], tags: list[tuple[str, dict]], scheme=None) -> str:
    scheme = scheme or current().schemes['ADR']
    prefix = prefix_for(scheme, scheme.view)
    table = TABLE_HEAD + '\n'.join((a.row(prefix) for a in adrs)) + '\n'
    from . import statuses
    if (declared := statuses.legend(scheme)):
        table = declared + '\n' + table
    stub = scheme.stub
    prose = stub.read_text() if stub.exists() else DEFAULT_STUB.replace('{title}', 'Architecture decision records' if scheme.prefix == 'ADR' else f'{scheme.prefix} documents')
    return prose.replace('{categories}', render_categories(adrs, tags, prefix)).replace('{table}', table)

def render_tag_page(tag: str, meta: dict, adrs: list[Adr], scheme=None) -> str:
    scheme = scheme or current().schemes['ADR']
    prefix = prefix_for(scheme, scheme.tag_dir)
    label = meta.get('label', tag.title())
    listed = [a for a in adrs if tag in a.tags]
    raw = meta.get('blurb') or ''
    blurb = f'\n{raw[:1].upper()}{raw[1:]}.\n' if raw else ''
    noun = 'decisions' if scheme.prefix == 'ADR' else f'{scheme.prefix} documents'
    return f'<!-- GENERATED by `luria index` — do not edit. -->\n\n# {scheme.prefix}s tagged `{tag}`\n{blurb}\n{len(listed)} of {len(adrs)} {noun}. Back to the [full index](../README.md).\n\n' + TABLE_HEAD + '\n'.join((a.row(prefix=prefix) for a in listed)) + '\n'

def render_document(scheme, docs: list[Adr]) -> str:
    stub = scheme.stub
    head = stub.read_text() if stub.exists() else DEFAULT_DOCUMENT_STUB.replace('{title}', f'{scheme.prefix} documents')
    base = scheme.output.parent if scheme.output else scheme.dir
    parts = []
    for doc in docs:
        body = parse_frontmatter(doc.path.read_text())[1].strip()
        label = doc.number if doc.number is not None else doc.code
        body = re.sub('^#\\s*[A-Z]+-[A-Za-z0-9]+\\s*(?::|—|-)\\s*', f'## {label}. ', body, count=1)
        slot = doc.number if doc.number is not None else doc.tail
        body = f'<a name="{doc.prefix.lower()}-{slot}"></a>\n\n{body}'
        meta = [f'*v{doc.version}']
        if doc.influenced_by:
            meta.append('shaped by ' + ', '.join((f'[{code}]({target})' if (target := _link(code, base)) else code for code in doc.influenced_by)))
        if doc.status != scheme.active:
            meta.append(f'**{doc.status}**')
        if (origin := str(doc.meta.get('origin', '')).strip()):
            meta.append(f"origin: {origin.rstrip('.')}")
        parts.append(f"{body}\n\n{' · '.join(meta)}*")
    return head.replace('{principles}', '\n\n'.join(parts))

def _link(code: str, base: Path) -> str:
    try:
        prefix, number = code.split('-')
        path = current().schemes[prefix.upper()].documents().get(int(number))
    except (ValueError, KeyError):
        return ''
    return os.path.relpath(path, base) if path else ''

def view_dirs() -> list[Path]:
    cfg = current()
    dirs: list[Path] = []
    for s in cfg.schemes.values():
        if s.render != 'index':
            continue
        dirs.append(s.tag_dir)
        if s.view != s.dir:
            dirs.append(s.view)
    dirs += [j.output for j in cfg.journals.values()]
    dirs.append(cfg.reports)
    return dirs

def orphans(rendered: dict[Path, str]) -> list[Path]:
    return [p for d in view_dirs() if d.is_dir() for p in sorted(d.glob('*.md')) if p not in rendered]

def ignored(paths: list[Path]) -> set[Path]:
    if not paths:
        return set()
    try:
        out = subprocess.run(['git', 'check-ignore', '--', *(str(p) for p in paths)], cwd=current().root, capture_output=True, text=True)
    except OSError:
        return set()
    if out.returncode not in (0, 1):
        return set()
    return {Path(line).resolve() for line in out.stdout.splitlines() if line}

def _render_scheme(scheme) -> dict[Path, str]:
    docs = load_scheme(scheme)
    if scheme.render == 'document':
        return {scheme.output: render_document(scheme, docs)} if scheme.output else {}
    tags = tag_order(docs, scheme)
    out = {scheme.index_path: render_index(docs, tags, scheme)}
    for tag, meta in tags:
        out[scheme.tag_dir / f'{tag}.md'] = render_tag_page(tag, meta, docs, scheme)
    return out

def outputs() -> dict[Path, str]:
    from . import config_doc, journal, record_doc, reports
    from .parallel import pmap
    cfg = current()
    units = [lambda s=s: _render_scheme(s) for s in cfg.schemes.values()]
    units += [lambda j=j: journal.outputs_for(j) for j in cfg.journals.values()]
    units += [reports.outputs]
    units += [record_doc.outputs]
    if cfg.owns_schema:
        units += [config_doc.outputs]
    out: dict[Path, str] = {}
    for rendered in pmap(lambda u: u(), units):
        out.update(rendered)
    return out

@dataclass(frozen=True)
class Staleness:
    stale: list[Path]
    orphaned: list[Path]
    badges: Path | None

    @property
    def all(self) -> list[Path]:
        return self.stale + self.orphaned + ([self.badges] if self.badges else [])

    @property
    def any(self) -> bool:
        return bool(self.all)

def staleness(rendered: dict[Path, str] | None=None) -> Staleness:
    from . import badges as badges_mod
    rendered = outputs() if rendered is None else rendered
    loose = orphans(rendered)
    skip = ignored(list(rendered) + loose)
    readme = badges_mod.readme()
    drifted = readme.exists() and readme not in skip and (badges_mod.OPEN in (text := readme.read_text())) and (badges_mod.rewrite(text) != text)
    return Staleness(stale=[p for p, text in rendered.items() if p not in skip and (not p.exists() or p.read_text() != text)], orphaned=[p for p in loose if p not in skip], badges=readme if drifted else None)

def run(check: bool=False) -> None:
    if not check:
        from . import config_doc, journal
        for j in current().journals.values():
            for p in journal.populate_created(j):
                print(f'populated `created:` from the path in {current().rel(p)}')
        for p in config_doc.retire():
            print(f"removed {current().rel(p)} — the configuration reference now renders only where its schema lives; this project's own record is described in {current().rel(current().record_doc)}")
    if check:
        report = staleness()
        if report.any:
            from . import ci
            print(f'stale ({ci.regenerate_remedy()}):', file=sys.stderr)
            for p in sorted(report.all):
                print(f'  {current().rel(p)}', file=sys.stderr)
            raise SystemExit(1)
        print('luria index: current')
        return
    rendered = outputs()
    cfg = current()
    for stale_file in orphans(rendered):
        stale_file.unlink()
    for p, text in rendered.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    from . import journal
    filed = {n: len(journal.entries(j)) for n, j in sorted(cfg.journals.items())}
    counted = ', '.join([f'{len(load_scheme(s))} {p}s' for p, s in sorted(cfg.schemes.items())] + [f"{c} {n} entr{('y' if c == 1 else 'ies')}" for n, c in filed.items()])
    print(f'Wrote {len(rendered)} file(s) from {counted}.')
    from . import badges
    readme = badges.readme()
    if readme.exists() and badges.OPEN in (text := readme.read_text()):
        readme.write_text(badges.rewrite(text))
if __name__ == '__main__':
    import fire
    fire.Fire(run)
