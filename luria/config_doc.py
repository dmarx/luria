def tables() -> list[type]:
    """Every config dataclass, in reading order.

    Derived for the same reason the rows are, and after the same failure: the
    list this replaced was hand-kept, and `chains` plus seven nested tables
    were missing from the reference for as long as they had existed. The rows
    inside a section were always safe; which sections existed at all was not,
    and a page can be wrong by omission as easily as by a wrong row (DP-3)."""
    found = [obj for name, obj in vars(config_mod).items()
             if isinstance(obj, type) and dataclasses.is_dataclass(obj)
             and obj.__module__ == config_mod.__name__
             and name not in NOT_A_TABLE]
    known = [cls for cls in ORDER if cls in found]
    return known + [cls for cls in found if cls not in known]


def sections() -> list[tuple[str, type, str]]:
    """(title, class, blurb) per section — membership from the schema.

    A class `PROSE` does not name still gets a section, headed by its own
    name: a reader learns the table exists and that nobody has described it,
    which beats learning nothing."""
    out = []
    for cls in tables():
        title, blurb = PROSE.get(cls, (f"`{cls.__name__}`", ""))
        out.append((title, cls, blurb))
    return out


