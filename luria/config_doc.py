#!/usr/bin/env python3
"""The configuration reference, rendered from the config schema itself.

    luria index                 # → <docs>/configuration.md, in Luria's own tree

It renders only where `luria/config.py` is a file the reader can open — see
`Config.owns_schema` (ADR-059). An adopting project gets `record.md` instead,
which describes the record *it* configured; this page is the schema, and the
schema is not theirs to maintain.

Luria's capability surface *is* `luria.yaml`: a scheme, a fragment directory, a
journal, a remote and the site are five composable primitives, and the ADR /
DP / changelog / devlog record this package ships is one instantiation of them
rather than a fixed set of parts. That was true long before this module
existed and was documented nowhere a reader arrives at in time — the prose
lived in `config.py`'s docstrings, and the reasoning lived in the decision
record, which is archaeology, not a reference.

Writing that page by hand would have made it the second copy of a schema that
changes — exactly the hand-maintained projection DP-3 says will drift. So it
is generated, and the load-bearing property is this: **the key tables come
from `dataclasses.fields()`, not from a list kept here.** Add a field to
`Site` and it appears in the reference on the next `luria index`; leave it
undocumented and the row still appears, with its type and default, because
the row was never something anyone had to remember to write.

The prose is this module's, not a per-project stub. A scheme's `README.stub`
exists because a project's decision index needs *its own* preamble; the
configuration reference is Luria describing its own schema, and that text is
identical in every repository that installs the package. A stub here would be
a file every adopter carried and none of them edited.

Three derivations, all mechanical:

- **Which sections exist** — `tables()` reads every dataclass out of
  `config.py`. This was a hand-kept list once, and it rotted exactly as one
  does: `chains` and seven nested tables — where `unique`, `alert`,
  `converse`, `invariant` and `required_when` all live — were absent from the
  reference for as long as they had existed, while every test passed, because
  each asked whether the sections listed were real rather than whether the
  real ones were listed. `ORDER` below is a reading order; anything it does
  not name is appended rather than dropped.
- **Dataclass sections** — `inspect.getdoc()` for the prose (those docstrings
  already carry worked YAML examples, so they stay the single source), plus a
  computed key table.
- **Plain-table sections** — `issue_url`, `paths`, `code`, `lint`, which have
  no dataclass behind them, render straight from `config.DEFAULTS`: keys from
  the schema, prose from `PLAIN`. A key nobody has described still gets a row,
  and `test_config_doc` fails until somebody writes one — the reminder lands
  in CI rather than in a reader's head.

The prose is the only hand-written part, and losing it is a blank cell rather
than a missing row. That asymmetry is the whole design: a table nobody
described renders undescribed, where a table nobody listed renders not at all.

The page registers in `Config.is_generated`, which is what makes it safe to
fill with example codes: `doc_refs.doc_files` filters on that flag, so the
bare-reference lint and `luria link --fix` both skip it, the same way they
skip the status reports.
"""

