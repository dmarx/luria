def plain_keys(subtree: str) -> list[str]:
    """The keys of one scalar table, read from `config.DEFAULTS`.

    A key whose default is a *dict* is usually a table in its own right —
    `paths`, `lint`, `schemes`, `chains` — and has its own section, so it is
    not also a row in the table above it.

    Usually, not always. A *free-form mapping* — `lint.baseline`, whose keys
    are warning-class names a project chooses — has no fixed shape, so nothing
    generates a section for it, and excluding it on the strength of its type
    dropped it out of the reference entirely and out of the "a key with no
    prose still gets a row" guard with it. The test for a table is whether
    something renders one, which is `SECTION_SUBTREES`, not whether the
    default happens to be a `dict`."""
    defaults = config_mod.DEFAULTS.get(subtree, {}) if subtree \
        else config_mod.DEFAULTS
    return [k for k, v in defaults.items()
            if not isinstance(v, dict) or k not in SECTION_SUBTREES]


# A run of 4-space-indented lines inside a docstring is a worked example. The
# docstrings write them as indented blocks because that is what reads well in
# a terminal; a fenced block is what reads well on a page.
_INDENTED = re.compile(r"(?m)^(?:    .*(?:\n|$))+")


def fence(text: str, lang: str = "yaml") -> str:
    """Indented example blocks in a docstring → fenced code blocks."""
    def swap(m: re.Match) -> str:
        body = "\n".join(line[4:] for line in m.group(0).rstrip("\n").split("\n"))
        return f"```{lang}\n{body}\n```\n"
    return _INDENTED.sub(swap, text)


# Presentation only — which fields are not keys a person writes. The key
# *list* is still `dataclasses.fields()`, so a field missing from these sets
# still gets a row; it is merely labelled `*required*` until someone
# classifies it, which is the safe direction to be wrong in.
FROM_TABLE_NAME: dict[type, set[str]] = {
    Scheme: {"prefix"},          # `schemes.ADR` → prefix "ADR"
    Journal: {"name"},           # `journals.devlog` → name "devlog"
    Remote: {"prefix"},          # …but `Remote.name` IS a key, deliberately
    RemoteScheme: {"prefix"},
}
DERIVED: dict[type, set[str]] = {
    Site: {"title", "base_url", "source_url"},   # …off `issue_url` (DP-3)
}


def rows(cls: type) -> list[tuple[str, str, str]]:
    """(key, type, default) for every public field of a config dataclass.

    The whole point of the module: this reads the schema rather than a list,
    so a field added to `Site` cannot be silently missing from the reference.

    The default shown is the *dataclass's* — the answer to "what do I get if I
    omit this key?", which is the question a reference is asked. What the
    shipped `luria.yaml` happens to set for its own ADR scheme is a different
    question, and answering it here would tell a project adding a second
    scheme that `output` defaults to `docs/decisions`, which is false."""
    out = []
    for f in dataclasses.fields(cls):
        if f.name.startswith("_"):
            continue
        if f.default is not dataclasses.MISSING:
            shown = f.default
        elif f.default_factory is not dataclasses.MISSING:  # type: ignore[misc]
            shown = f.default_factory()  # type: ignore[misc]
        else:
            shown = dataclasses.MISSING
        if f.name in FROM_TABLE_NAME.get(cls, ()):
            label = "*the table's own name*"
        elif f.name in DERIVED.get(cls, ()):
            label = "*derived from `issue_url`*"
        else:
            label = _render_default(shown)
        out.append((f.name, str(f.type), label))
    return out


def _render_default(value) -> str:
    if value is dataclasses.MISSING:
        return "*required*"
    if value in ((), [], {}, "", None):
        return "*unset*"
    return f"`{value!r}`" if not isinstance(value, str) else f"`\"{value}\"`"


def table(cls: type) -> str:
    # `escape_cell` because a union annotation carries the same `|` markdown
    # uses for a column boundary — `Path | None` silently becomes two columns
    # otherwise, and every row below it shifts.
    lines = ["| key | type | default |", "|---|---|---|"]
    for name, type_, default in rows(cls):
        lines.append(f"| `{name}` | `{escape_cell(type_)}` | {default} |")
    return "\n".join(lines) + "\n"


def plain_table(keys: list[str], defaults: dict, prose: dict[str, str]) -> str:
    """One scalar table. `keys` is the schema's, `prose` is a person's.

    A key with no prose renders with an empty description rather than not at
    all — the stamp's promise, and the only behaviour under which the page
    cannot quietly lose a key nobody got around to writing about."""
    lines = ["| key | default | what it does |", "|---|---|---|"]
    for name in keys:
        lines.append(f"| `{name}` | {_render_default(defaults.get(name, ''))} "
                     f"| {prose.get(name, '')} |")
    return "\n".join(lines) + "\n"


def render() -> str:
    parts = [HEADER.format(stamp=STAMP)]

    for title, subtree, blurb, prose in PLAIN:
        defaults = config_mod.DEFAULTS.get(subtree, {}) if subtree \
            else config_mod.DEFAULTS
        parts.append(f"\n## {title}\n")
        if blurb:
            parts.append(f"\n{blurb}\n")
        parts.append("\n" + plain_table(plain_keys(subtree), defaults, prose))

    # `sections()`, not the `SECTIONS` snapshot: the page is rendered from
    # the schema as it is at render time, and a module-level constant is one
    # more copy that could be the stale one.
    for title, cls, blurb in sections():
        parts.append(f"\n## {title}\n\n{blurb}\n\n")
        parts.append(fence(inspect.getdoc(cls) or "").rstrip("\n") + "\n\n")
        parts.append(table(cls))

    parts.append(FOOTER)
    return "".join(parts)


def outputs(out_dir: Path | None = None) -> dict[Path, str]:
    """The reference, keyed by where it lands — the unit `luria index`
    renders, so a stale page fails the same check as every other view."""
    cfg = current()
    path = cfg.config_doc if out_dir is None else out_dir / "configuration.md"
    return {path: render()}


def retire() -> list[Path]:
    """Remove a configuration reference this project no longer generates.

    Until ADR-059 the page rendered into every adopting project, so an upgrade
    leaves one behind: a vendored copy of Luria's schema, already a release out
    of date, with nothing in the repository responsible for keeping it true.
    Left alone it is worse than absent, because it reads as current.

    Deleting a file in somebody else's repository wants a reason better than
    "we stopped writing it", so the guard is the generator's own marker: its
    presence is proof Luria wrote this file, and its absence means the path is
    the project's own prose and is left exactly where it is."""
    cfg = current()
    path = cfg.config_doc
    if cfg.owns_schema or not path.exists():
        return []
    if MARKER not in path.read_text(encoding="utf-8"):
        return []
    path.unlink()
    return [path]


def write(out_dir: Path | None = None) -> list[Path]:
    rendered = outputs(out_dir)
    for path, text in rendered.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return sorted(rendered)


