# luria/pattern_reports.py
"""A named path pattern rendered as a page of its matches (#373).

    patterns:
      unopposed:
        match: >-
          (c:CLAIM {role: 'thesis'}) WHERE NOT (c)<-[:objects_to]-(:CLAIM)
        output: docs/unopposed.md

A chain shows a pattern only as steps inside its lines, and only a pattern
that runs from the chain's scheme back to it. Most of what a record wants to
ask has neither shape — a thesis nothing objects to, an argument something
undercuts, a step the record calls unfinished — and the answer is a list.
This is that list: one row per match, one column per named node, in the
order the pattern writes them.

**What a page promises.** Every cell links to its document from the page's
own directory and carries its title. Rows are sorted by their codes, column
by column, and nothing on the page reads the clock, so `luria index --check`
can hold it fresh like any other view. A pattern that matches nothing says
"No matches" rather than rendering a table with no rows, because an empty
table reads like a page that failed to build (DP-15).

**A report, never a failure.** Whether a match matters is a judgement, so no
lint class reads this page; and it is excluded from the reference scan, since
it lists retired documents as readily as live ones (`Config.is_generated`).
"""
from __future__ import annotations

from .adr_index import Adr, escape_cell, load_scheme, prefix_for
from .config import current
from .contract import local_scheme
from . import pattern_rules

MARKER = "<!-- GENERATED by `luria index` — do not edit. -->"


def _documents(codes: set[str]) -> dict[str, Adr]:
    """Every document a page cites, by code, loading each scheme once."""
    out: dict[str, Adr] = {}
    for prefix in {local_scheme(c) for c in codes} - {None}:
        out.update((d.code, d) for d in load_scheme(current().schemes[prefix]))
    return out


def _cell(code: str, docs: dict[str, Adr], base) -> str:
    doc, prefix = docs.get(code), local_scheme(code)
    if doc is None or prefix is None:
        return escape_cell(code)
    scheme = current().schemes[prefix]
    link = prefix_for(scheme, base) + doc.path.name
    return f"[{code}]({link}) — {escape_cell(doc.title)}"


def _count(n: int) -> str:
    return f"{n} match" + ("" if n == 1 else "es")


def render(spec) -> str:
    """One pattern's page."""
    cols = pattern_rules.columns(spec.parsed)
    rows = pattern_rules.matches(spec.name)
    title = spec.title or spec.name.replace("_", " ").capitalize()
    out = [MARKER, "", f"# {title}", ""]
    if spec.blurb:
        out += [spec.blurb, ""]
    out += [f"`{spec.match}` · {_count(len(rows))}", ""]
    if not rows:
        return "\n".join(out + ["No matches."]) + "\n"
    docs = _documents({code for row in rows for code in row})
    base = spec.output.parent
    out.append("| " + " | ".join(f"{var} ({label})" for var, label in cols)
               + " |")
    out.append("|" + "---|" * len(cols))
    out += ["| " + " | ".join(_cell(code, docs, base) for code in row) + " |"
            for row in rows]
    return "\n".join(out) + "\n"


def outputs() -> dict:
    """Every pattern page, for `luria index` to write and `--check` to
    compare — none for a record whose patterns declare no `output`."""
    return {spec.output: render(spec)
            for spec in current().patterns.values() if spec.output}
