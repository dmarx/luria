# luria/views.py
"""A view written as a Jinja template over the record (ADR-130).

    views:
      bootloader:
        template: record/views.d/CLAUDE.md.j2
        output: CLAUDE.md

Every other view luria renders is a generator in this package, one per
shape. A project that wanted any other projection of its record, such as an
agent's bootloader that restates the config or a manuscript built from its
claims, wrote it by hand and watched it drift (DP-2). A template keeps the
prose hand-written and derives the facts.

Three rules do the work.

**The record is read, never spelled.** A template asks for a document with
`doc`, a set with `docs`, a vocabulary with `vocabulary` and the schemes with
`schemes`. A code, a field or a part that does not exist is a render error
naming the template's line, never an empty string (`StrictUndefined`).

**No template spells a link target.** It writes codes bare. The output goes
through `doc_refs.linkify` in the output's own frame, which is the same
resolver `luria link --fix` uses. Text a template transcludes (a body, a
part, a summary) carries links written for its source's frame, so it is
rebased to the output's frame first.

**A view is a pure function of the tree.** The sandbox exposes no clock, no
environment and nothing but the loader on disk. That is ADR-035's rule for
reports, and it is what lets `luria index --check` call a view stale.

Composition is Jinja's own: `include`, `import` and `extends` resolve from
the project root, so a mostly hand-written file is a template that is mostly
prose.

A template named `luria:NAME` is one of luria's own (`view_templates/`),
given its values as `context`: a pattern's page is such a view (#373).

`outline(names)` merges the matches of one or several patterns into one
tree by shared prefix, and the `step` filter renders a document as a chain
page renders a step, `[CODE](link) — title *(facets)*`, so a pattern page's
outline and a chain read the same.
"""

from __future__ import annotations

import hashlib
import os
import sys
import traceback
from dataclasses import dataclass
from pathlib import Path

import jinja2
from jinja2.sandbox import SandboxedEnvironment

from .config import current
from .view_document import (Document, Read, Site, _Refused, _site, stable,
                            _Undefined)

STAMP = ("<!-- GENERATED by `luria index` from {template} — edit the "
         "template, not this file. -->\n\n")
# A supplied view has no template to edit; its stamp names the config key.
SUPPLIED_STAMP = ("<!-- GENERATED by `luria index` from {origin} in "
                  "luria.yaml — edit that, not this file. -->\n\n")
PACKAGE_TEMPLATES = Path(__file__).parent / "view_templates"

class ViewError(Exception):
    """A view that cannot render, said once, with the template's line."""


@dataclass(frozen=True)
class Term:
    """One value of a vocabulary, as a template reads it."""
    value: str
    label: str
    blurb: str


@dataclass(frozen=True)
class SchemeInfo:
    """What a template may say about a scheme: what it calls itself, where
    its documents are filed and where its view renders, both relative to
    the project root."""
    prefix: str
    title: str
    blurb: str
    dir: str
    output: str
    # "index" (a table and per-value pages under `output`) or "document"
    # (the bodies assembled into the one page `output`).
    render: str = "index"


@dataclass(frozen=True)
class OutputInfo:
    """A chain or a view, as a template names it: its name, its title where
    it has one, and the page it renders into, relative to the project root."""
    name: str
    title: str
    output: str


@dataclass(frozen=True)
class PathsInfo:
    """The pages and directories luria renders at fixed, configured places,
    relative to the project root."""
    docs: str
    reports: str
    record: str             # the record description
    configuration: str      # the configuration reference


@dataclass(frozen=True)
class JournalInfo:
    """The same for a journal: where entries are filed, where books land."""
    name: str
    title: str
    blurb: str
    dir: str
    output: str


@dataclass(frozen=True)
class Step:
    """One node of an outline: how deep it sits, and its document (or its
    code, when it names no document in this record)."""
    depth: int
    doc: object


@dataclass(frozen=True)
class Outline:
    """Matches merged into one tree, in render order, and how many matches
    each pattern contributed."""
    steps: list
    counts: dict


@dataclass(frozen=True)
class Rendering:
    """One view's output, and what producing it read."""
    text: str
    reads: dict[str, Read]


def _prefix(source_frame: Path, out_dir: Path) -> str:
    rel = Path(os.path.relpath(source_frame, out_dir)).as_posix()
    return "" if rel == "." else rel + "/"


class _Record:
    """The functions a template calls, bound to one output's frame."""

    def __init__(self, output: Path):
        self.cfg = current()
        self.out_dir = output.parent
        self._contracts: dict[str, object] = {}
        self._reads: dict[str, tuple] = {}

    def saw(self, document: Document, kind: str, value=None) -> None:
        """Record that the template read `value` from `document` here."""
        template, line = _site()
        _, sites, digest = self._reads.setdefault(
            document.code, (document._adr, [], hashlib.sha256()))
        digest.update(stable(value).encode("utf-8") + b"\0")
        site = Site(template, line, kind)
        if site not in sites:
            sites.append(site)

    def reads(self) -> dict[str, Read]:
        out = {}
        for code, (adr, sites, digest) in self._reads.items():
            status = adr.status_value
            word = adr.scheme.retires_on
            out[code] = Read(code, status, bool(word) and status == word,
                             tuple(adr.superseded_by), tuple(sites),
                             digest.hexdigest())
        return out

    def contract(self, scheme):
        """The scheme's contract, compiled once per render."""
        from .contract import for_scheme
        if scheme.prefix not in self._contracts:
            self._contracts[scheme.prefix] = for_scheme(scheme)
        return self._contracts[scheme.prefix]

    def prefix(self, path: Path) -> str:
        """What rebases a link written in `path` to the output's frame."""
        return _prefix(self.cfg.link_base(path), self.out_dir)

    def resolve(self, code: str) -> "Document | str":
        """The document `code` names, or the code itself when it names none
        in this record: a remote's, or a dangling one the lint reports."""
        from .adr_index import Adr
        from .referents import path_of
        path = path_of(code)
        if path is None:
            return str(code)
        prefix = str(code).partition("-")[0].upper()
        return Document(Adr(path, self.cfg.schemes[prefix]), self)

    def doc(self, code: str) -> Document:
        found = self.resolve(code)
        if not isinstance(found, Document):
            raise _Refused(f"{code} names no document in this record")
        return found

    def docs(self, prefix: str, in_force: bool | None = None,
             **where) -> list[Document]:
        """A scheme's documents in code order, filtered on fields read as
        the contract reads them. `in_force=True` keeps the documents whose
        status is the scheme's own `active` word, `False` the rest, so a
        template need not spell a word each scheme chooses for itself."""
        from .adr_index import load_scheme
        scheme = self.cfg.schemes.get(str(prefix).upper())
        if scheme is None:
            raise _Refused(f"{prefix} is no scheme in this record "
                           f"(schemes: {', '.join(sorted(self.cfg.schemes))})")
        contract = self.contract(scheme)
        return [Document(a, self) for a in load_scheme(scheme)
                if (in_force is None
                    or (a.status_value == scheme.active) == bool(in_force))
                and all(_holds(contract, a.meta, k, v)
                        for k, v in where.items())]

    def match(self, pattern: str) -> list[dict[str, Document]]:
        """Every match of a path pattern, as a row mapping each named node
        to its document, ordered by those codes in the order the nodes are
        named. `pattern` is a pattern `luria.yaml` declares, by name, or one
        written here in the same syntax and checked the same way."""
        from . import logic, pattern_rules
        parsed = _pattern(self.cfg, pattern)
        named = [var for var, _ in parsed.named]
        if not named:
            raise _Refused(f"`{pattern}` names no node, so a match has "
                           "nothing to show — name one, as in `(c:CLAIM)`")
        text = pattern_rules.program({parsed.name: parsed}, rows=True)
        families = (frozenset({"values"})
                    if pattern_rules.needs_values({parsed.name: parsed})
                    else frozenset())
        found: dict[str, dict[str, str]] = {}
        for _, key, var, code in logic.derive(
                "relations", extra=text,
                families=families).get("pattern_row", ()):
            found.setdefault(key, {})[var] = code
        # Matches differing only in an anonymous node are one row.
        rows = {tuple(row.get(v, "") for v in named): row
                for row in found.values()}
        return [{v: self.resolve(rows[k][v]) for v in named if v in rows[k]}
                for k in sorted(rows)]

    def outline(self, patterns) -> "Outline":
        """The matches of one or several patterns as one tree.

        A match is the path of its named nodes, in pattern order, and the
        tree merges every shared prefix: a node renders once per distinct
        path to it, under its parent, children and roots in code order.
        Patterns merge by position, not by variable name, so a short pattern
        that is a prefix of a longer one is the same nodes: the longer one
        hangs its extra nodes under the shorter one's."""
        names = [patterns] if isinstance(patterns, str) else list(patterns)
        counts: dict[str, int] = {}
        # Each distinct prefix, by its codes, to the document it ends on.
        nodes: dict[tuple[str, ...], object] = {}
        for name in names:
            named = [var for var, _ in _pattern(self.cfg, name).named]
            rows = self.match(name)
            counts[name] = len(rows)
            for row in rows:
                path = [row[v] for v in named if v in row]
                codes = tuple(getattr(d, "code", None) or str(d) for d in path)
                for k in range(1, len(path) + 1):
                    nodes.setdefault(codes[:k], path[k - 1])
        # Sorting the prefixes puts each node after its parent and its
        # siblings in code order: the outline in reading order.
        steps = [Step(len(key) - 1, nodes[key]) for key in sorted(nodes)]
        return Outline(steps, counts)

    def step(self, document, facet_by=("status",)) -> str:
        """One step as a chain page renders it (`steps.step`), linked from
        this output: `[CODE](link) — title *(facets)*`."""
        from . import steps
        if not isinstance(document, Document):
            return str(document)
        text = steps.step(document._adr, self.out_dir, tuple(facet_by))
        self.saw(document, "read", text)
        return text

    def vocabulary(self, name: str) -> list[Term]:
        values = self.cfg.vocabularies.get(name)
        if values is None:
            raise _Refused(f"{name} is no vocabulary in this record "
                           f"(vocabularies: "
                           f"{', '.join(sorted(self.cfg.vocabularies))})")
        return [Term(str(v), str((m or {}).get("label") or v),
                     str((m or {}).get("blurb") or ""))
                for v, m in values.items()]

    def schemes(self) -> list[SchemeInfo]:
        return [SchemeInfo(s.prefix, str(s.title or ""),
                           str(s.blurb or "").strip(), self.cfg.rel(s.dir),
                           self.cfg.rel(s.output) if s.output else "",
                           s.render)
                for s in self.cfg.schemes.values()]

    def chains(self) -> list[OutputInfo]:
        return [OutputInfo(c.name, c.title, self.cfg.rel(c.output))
                for c in self.cfg.chains.values()]

    def views(self) -> list[OutputInfo]:
        return [OutputInfo(v.name, v.name, self.cfg.rel(v.output))
                for v in self.cfg.views.values()]

    def paths(self) -> PathsInfo:
        return PathsInfo(self.cfg.rel(self.cfg.docs),
                         self.cfg.rel(self.cfg.reports),
                         self.cfg.rel(self.cfg.record_doc),
                         self.cfg.rel(self.cfg.config_doc))

    def journals(self) -> list[JournalInfo]:
        return [JournalInfo(j.name, str(j.title or ""),
                            str(j.blurb or "").strip(), self.cfg.rel(j.dir),
                            self.cfg.rel(j.output))
                for j in self.cfg.journals.values()]


def _pattern(cfg, source: str):
    """A declared pattern by name, or `source` parsed and checked against
    the schemes exactly as a declared one is (`config._patterns`)."""
    from . import consistency
    from .config import NamedPattern
    from .patterns import parse
    if source in cfg.patterns:
        return cfg.patterns[source].parsed
    name = "match"
    try:
        named = NamedPattern(name=name, match=source.strip(),
                             _parsed=parse(name, source))
        consistency.check_patterns({name: named}, cfg.schemes)
    except ValueError as exc:
        raise _Refused(str(exc).replace(
            f"luria.yaml: patterns.{name}: ", "")) from None
    return named.parsed


def _holds(contract, meta: dict, field: str, wanted) -> bool:
    """Whether the field, read as the contract reads it, holds `wanted`. A
    list field holds each of its values, and `status` is its value."""
    return str(wanted) in [str(v) for v in contract.reading(field, meta)]


def _environment() -> SandboxedEnvironment:
    """One environment per render: the loader reads the tree as it is now,
    and nothing survives from one view to the next."""
    env = SandboxedEnvironment(
        # luria's own `luria:` templates first, so a project cannot shadow one.
        loader=jinja2.ChoiceLoader([
            jinja2.PrefixLoader(
                {"luria": jinja2.FileSystemLoader(str(PACKAGE_TEMPLATES))},
                delimiter=":"),
            jinja2.FileSystemLoader(str(current().root)),
        ]),
        undefined=_Undefined,
        autoescape=False,
        keep_trailing_newline=True,
        trim_blocks=True,
        lstrip_blocks=True,
    )
    from .adr_index import escape_cell
    env.filters["cell"] = escape_cell
    return env


def _name(view) -> str:
    if isinstance(view.template, str):         # `luria:NAME`
        return view.template
    return current().rel(view.template).replace(os.sep, "/")


def _located(view, exc: BaseException) -> ViewError:
    """`exc` as one line naming the template file and line it came from."""
    if isinstance(exc, jinja2.TemplateSyntaxError):
        where = f"{exc.name or _name(view)}:{exc.lineno}"
        return ViewError(f"{where}: {exc.message}")
    root = str(current().root)
    ours = str(PACKAGE_TEMPLATES)
    where = _name(view)
    for frame in reversed(traceback.extract_tb(exc.__traceback__)):
        if frame.filename.endswith(".py"):
            continue
        if frame.filename.startswith(ours):
            where = (f"luria:{Path(frame.filename).relative_to(ours).as_posix()}"
                     f":{frame.lineno}")
            break
        if frame.filename.startswith(root):
            where = (f"{Path(frame.filename).relative_to(root).as_posix()}"
                     f":{frame.lineno}")
            break
    if isinstance(exc, jinja2.TemplateNotFound):
        return ViewError(f"{where}: no template {exc.name!r} under the "
                         "project root")
    return ViewError(f"{where}: {exc}")


# The last rendering of each output in this process. A lint renders every
# view to build the view tree, then asks what each read; the text it holds
# says whether the rendering here is the one it means.
_RENDERED: dict[Path, Rendering] = {}


def rendering(view, text: str | None = None) -> Rendering:
    """`view` rendered, with what it read. Given the text a caller already
    rendered, the rendering that produced it is reused rather than redone."""
    held = _RENDERED.get(view.output)
    if text is not None and held is not None and held.text == text:
        return held
    render(view)
    return _RENDERED[view.output]


def render(view) -> str:
    """The text `view` renders to, linked and stamped. Raises ViewError."""
    from . import doc_refs
    record = _Record(view.output)
    env = _environment()
    env.globals.update(doc=record.doc, docs=record.docs,
                       vocabulary=record.vocabulary, schemes=record.schemes,
                       match=record.match, outline=record.outline,
                       journals=record.journals, chains=record.chains,
                       views=record.views, paths=record.paths)
    env.filters["step"] = record.step
    try:
        text = env.get_template(_name(view)).render(view.context)
    except (jinja2.TemplateError, _Refused, TypeError, ValueError,
            AttributeError, KeyError, LookupError) as exc:
        raise _located(view, exc) from None
    text, _ = doc_refs.linkify(text, view.output)
    if view.output.suffix == ".md":
        text = (SUPPLIED_STAMP.format(origin=view.where) if view.origin
                else STAMP.format(template=_name(view))) + text
    _RENDERED[view.output] = Rendering(text, record.reads())
    return text


def outputs(skip_broken: bool = False) -> dict[Path, str]:
    """Every view, rendered. A broken one raises unless `skip_broken`, which
    is for the lint: it reports the failure itself (`errors`) and needs every
    other view to go on checking."""
    from . import view_pins
    out: dict[Path, str] = {}
    for view in current().views.values():
        # A pinned view holds its committed output: it is what was endorsed,
        # and `view_pins.drift_rows` says when the record has moved under it.
        if (kept := view_pins.held(view)) is not None:
            out[view.output] = kept
            continue
        try:
            out[view.output] = render(view)
        except ViewError:
            if not skip_broken:
                raise
    return out


def errors(rendered: dict[Path, str] | None = None) -> list[str]:
    """One line per view that does not render. Given what the lint already
    rendered, only the views missing from it are rendered again, so a lint
    renders a working view once."""
    found = []
    for view in current().views.values():
        if rendered is not None and view.output in rendered:
            continue
        try:
            render(view)
        except ViewError as exc:
            found.append(f"{view.where}: {exc}")
    return found


if __name__ == "__main__":
    for line in errors():
        print(line, file=sys.stderr)
