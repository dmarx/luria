# tests/test_bootloader_view.py
"""This repository's own `CLAUDE.md` is a view (ADR-130): the hand-written
map stays prose in its template, and the principles it lists are derived,
so the bootloader cannot name a principle that was retired or miss one
that was adopted.
"""

from __future__ import annotations

from luria import adr_index, config, views


def bootloader():
    return config.current().views["bootloader"]


def test_claude_md_is_rendered_from_a_template():
    view = bootloader()
    root = config.current().root
    assert view.output == root / "CLAUDE.md"
    assert view.template == root / "record/views.d/CLAUDE.md.j2"


def test_it_lists_exactly_the_principles_in_force():
    text = views.render(bootloader())
    section = text.split("## Principles in force", 1)[1]
    for scheme in [config.current().schemes["DP"]]:
        for doc in adr_index.load_scheme(scheme):
            listed = f"[{doc.code}]" in section
            assert listed == (doc.status_value == scheme.active), doc.code


def test_it_keeps_the_hand_written_map():
    text = views.render(bootloader())
    assert "This file is a map, not a manual" in text
    assert "## Working agreements" in text
    assert text.startswith("<!-- GENERATED by `luria index` from "
                           "record/views.d/CLAUDE.md.j2")
