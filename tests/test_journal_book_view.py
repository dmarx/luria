# tests/test_journal_book_view.py
"""The journal book is a template luria ships (ADR-147), and its output
did not move.

The migration's promise is byte-identical output: the generator keeps its data
half, the markup moves to `luria:journal-book.md.j2`, and a reader of any book
sees no difference. So the oracle is the generator as it was, copied here
verbatim, and the new path is compared against it on trees built to exercise
each branch of the old code and on every book this repository files.
"""
import datetime as dt
from pathlib import Path

import pytest

from luria import journal, slugs
from luria.config import Journal, current

from test_journal import file_entry, jrnl


def _legacy_sections(j: Journal, filed) -> list[str]:
    """`journal._sections` before the migration, verbatim."""
    out = []
    for entry in filed:
        out.append("\n".join(
            ["---", "", f'<a id="{entry.anchor}"></a>', "",
             f"## {entry.title}", "",
             f"*{entry.created.strftime('%Y-%m-%d %H:%M:%S')}"
             + (" · " + " · ".join(entry.tags) if entry.tags else "")
             + "*", "", entry.body, ""]))
    return out


def _legacy_heading_text(j: Journal, filed) -> str:
    label = filed[0].created.strftime(journal.LABELS[j.granularity]).lstrip("0")
    return f"# {j.title} — {label}\n\n## Contents\n"


def _legacy_entry_anchors(j: Journal, filed) -> dict[str, str]:
    """`journal.entry_anchors` before the migration, verbatim."""
    slugger = slugs.Slugger()
    for h in slugs.headings(_legacy_heading_text(j, filed)):
        slugger.slug(h)
    out = {}
    for entry, section in zip(filed, _legacy_sections(j, filed)):
        for i, h in enumerate(slugs.headings(section)):
            got = slugger.slug(h)
            if i == 0:
                out[entry.anchor] = got
    return out


def legacy_render_book(j: Journal, key: str, filed) -> str:
    """`journal.render_book` before the migration, verbatim, with its helpers
    copied above — the oracle must not call the code it is checking."""
    label = filed[0].created.strftime(journal.LABELS[j.granularity]).lstrip("0")
    anchors = _legacy_entry_anchors(j, filed)
    lines = [f"<!-- GENERATED by `luria index` from {j.rel_dir}/ — "
             "edit the entries, not this file. -->", "",
             f"# {j.title} — {label}", "",
             f"{len(filed)} entr{'y' if len(filed) == 1 else 'ies'}. "
             f"[All books](README.md).", "", "## Contents", ""]
    for entry in filed:
        stamp = entry.created.strftime("%d %b %H:%M").lstrip("0")
        lines.append(
            f"- [{stamp} — {entry.title}](#{anchors[entry.anchor]})")
    lines.append("")
    lines += _legacy_sections(j, filed)
    return "\n".join(lines)


def test_the_oracle_can_fail(tmp_path, monkeypatch):
    """A positive control (DP-015): change one byte of the shipped section
    markup and the comparison must notice, or it is comparing nothing."""
    j = jrnl(tmp_path)
    file_entry(j, "2026-05-01T00:00:00", "Alone", tags=["retro"])
    filed = journal.books(j)["2026-05"]
    real = journal._entry_context
    monkeypatch.setattr(journal, "_entry_context",
                        lambda e, slug="": {**real(e, slug), "created": "X"})
    assert journal.render_book(j, "2026-05", filed) != \
        legacy_render_book(j, "2026-05", filed)


def _same_for_every_book(j: Journal) -> int:
    grouped = journal.books(j)
    for key, filed in grouped.items():
        assert journal.render_book(j, key, filed) == \
            legacy_render_book(j, key, filed), key
    return len(grouped)


@pytest.mark.parametrize("granularity", ["year", "month", "day"])
def test_every_granularity_renders_as_before(tmp_path, granularity):
    j = jrnl(tmp_path, granularity)
    file_entry(j, "2026-01-02T03:04:05", "First", tags=["retro", "earmarked"])
    file_entry(j, "2026-01-02T09:00:00", "Same day, no tags")
    file_entry(j, "2026-03-04T05:06:07", "A later month",
               body="## A heading inside the body\n\nText.")
    file_entry(j, "2027-12-31T23:59:59", "A later year")
    assert _same_for_every_book(j) > 0


def test_a_book_of_one_entry_renders_as_before(tmp_path):
    j = jrnl(tmp_path)
    file_entry(j, "2026-05-01T00:00:00", "Alone")
    assert _same_for_every_book(j) == 1


def test_repeated_titles_keep_their_distinct_slugs(tmp_path):
    """The contents list links each heading's slug, and a repeated title is
    the case where a slug depends on everything before it."""
    j = jrnl(tmp_path)
    for minute in range(3):
        file_entry(j, f"2026-06-01T10:0{minute}:00", "Same title",
                   body="## Same title\n\nA body heading with the same text.")
    assert _same_for_every_book(j) == 1


def test_every_book_this_repository_files_is_unchanged():
    """The real corpus: every entry luria's own record has filed. The count
    is asserted before the comparison is believed — an empty journal would
    compare equal too (DP-015)."""
    checked = sum(_same_for_every_book(j) for j in current().journals.values())
    assert checked > 0


def test_the_markup_lives_in_the_template_not_the_generator():
    """What the migration moves: the book's markup is the shipped template's,
    so a change to the page is a change to one file a project can read."""
    template = Path(journal.__file__).parent / "view_templates" / "journal-book.md.j2"
    assert template.is_file()
    assert "## Contents" in template.read_text(encoding="utf-8")
    import inspect
    assert "## Contents" not in inspect.getsource(journal.render_book)
