# tests/test_pattern_outline.py
"""A pattern page as an outline: matches nest by shared prefix, patterns
sharing an output merge into one tree, and a step reads as a chain's does."""
from __future__ import annotations

import os
from pathlib import Path

import pytest

from _config import merged
from luria import chains, config, views

BASE = """
issue_url: https://example.test/issues/{n}
vocabularies:
  roles:
    thesis: {blurb: a position}
    objection: {blurb: against a position}
schemes:
  CLAIM:
    dir: record/claims.d
    output: docs/claims
    fields:
      role: {vocabulary: roles}
    references:
      undercuts: {scheme: ARG, many: true, required: false}
  ARG:
    dir: record/args.d
    output: docs/args
    references:
      concludes: {scheme: CLAIM, required: false}
"""

BARE = "(c:CLAIM)<-[:concludes]-(g:ARG)"
UNDERCUT = "(c:CLAIM)<-[:concludes]-(g:ARG)<-[:undercuts]-(u:CLAIM)"
OUT = "docs/dialectic-outline.md"


def dialectic(**extra) -> dict:
    """`bare` and `undercut` sharing one output; `extra` per pattern."""
    return {"patterns": {
        "bare": {"match": BARE, "output": OUT, **extra.get("bare", {})},
        "undercut": {"match": UNDERCUT, "output": OUT,
                     **extra.get("undercut", {})}}}


def project(tmp_path: Path, monkeypatch, *extra) -> Path:
    (tmp_path / "luria.yaml").write_text(merged(BASE, *extra))
    monkeypatch.setenv("LURIA_ROOT", str(tmp_path))
    config.reset()
    return tmp_path


def doc(root: Path, code: str, title: str, **fields) -> None:
    folder = {"CLAIM": "claims.d", "ARG": "args.d"}[code.split("-")[0]]
    front = ["---", f"status: {fields.pop('status', 'Active')}",
             f"title: {title!r}", "date: '2026-01-01'"]
    for k, v in fields.items():
        if isinstance(v, list):
            front += [f"{k}:"] + [f"- {x}" for x in v]
        else:
            front.append(f"{k}: {v}")
    front += ["---", "", f"# {code}: {title}", "", "Body."]
    path = root / "record" / folder / f"{code}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(front) + "\n")


def record(root: Path) -> None:
    doc(root, "CLAIM-001", "Thesis A", role="thesis")
    doc(root, "CLAIM-002", "Thesis B", role="thesis")
    doc(root, "CLAIM-003", "Undercutter one", role="objection",
        undercuts=["ARG-001"])
    doc(root, "CLAIM-004", "Undercutter two", role="objection",
        undercuts=["ARG-001", "ARG-003"], status="Proposed")
    doc(root, "CLAIM-005", "Concluded by nothing", role="thesis")
    doc(root, "ARG-001", "Undercut twice", concludes="CLAIM-001")
    doc(root, "ARG-002", "Undercut by nothing", concludes="CLAIM-001")
    doc(root, "ARG-003", "Undercut once", concludes="CLAIM-002")


def page(root: Path, out: str = OUT) -> str:
    return views.outputs()[root / out]


def outline(text: str) -> list[str]:
    return [line for line in text.splitlines() if line.lstrip().startswith("- [")]


C = "../record/claims.d/"
A = "../record/args.d/"


def test_patterns_sharing_an_output_merge_into_one_outline(
        tmp_path, monkeypatch):
    """The case #380 was written for: every argument at depth 2 under its
    conclusion, undercut or not, each undercutter at depth 3."""
    root = project(tmp_path, monkeypatch, dialectic())
    record(root)
    text = page(root)
    assert outline(text) == [
        f"- [CLAIM-001]({C}CLAIM-001.md) — Thesis A *(Active)*",
        f"  - [ARG-001]({A}ARG-001.md) — Undercut twice *(Active)*",
        f"    - [CLAIM-003]({C}CLAIM-003.md) — Undercutter one *(Active)*",
        f"    - [CLAIM-004]({C}CLAIM-004.md) — Undercutter two *(Proposed)*",
        f"  - [ARG-002]({A}ARG-002.md) — Undercut by nothing *(Active)*",
        f"- [CLAIM-002]({C}CLAIM-002.md) — Thesis B *(Active)*",
        f"  - [ARG-003]({A}ARG-003.md) — Undercut once *(Active)*",
        f"    - [CLAIM-004]({C}CLAIM-004.md) — Undercutter two *(Proposed)*",
    ]
    assert "**bare** · `" + BARE + "` · 3 matches" in text
    assert "**undercut** · `" + UNDERCUT + "` · 3 matches" in text
    assert text.startswith(
        "<!-- GENERATED by `luria index` from patterns.bare and "
        "patterns.undercut in luria.yaml — edit that, not this file. -->")
    assert "# Bare\n" in text


def test_one_pattern_nests_its_matches_by_shared_prefix(tmp_path, monkeypatch):
    """A shared prefix renders once; siblings and roots sort by code."""
    root = project(tmp_path, monkeypatch, {"patterns": {"undercut": {
        "match": UNDERCUT, "output": OUT, "title": "Undercut",
        "blurb": "Arguments something undercuts."}}})
    record(root)
    text = page(root)
    assert outline(text) == [
        f"- [CLAIM-001]({C}CLAIM-001.md) — Thesis A *(Active)*",
        f"  - [ARG-001]({A}ARG-001.md) — Undercut twice *(Active)*",
        f"    - [CLAIM-003]({C}CLAIM-003.md) — Undercutter one *(Active)*",
        f"    - [CLAIM-004]({C}CLAIM-004.md) — Undercutter two *(Proposed)*",
        f"- [CLAIM-002]({C}CLAIM-002.md) — Thesis B *(Active)*",
        f"  - [ARG-003]({A}ARG-003.md) — Undercut once *(Active)*",
        f"    - [CLAIM-004]({C}CLAIM-004.md) — Undercutter two *(Proposed)*",
    ]
    assert text.count("[CLAIM-001](") == 1 and text.count("[ARG-001](") == 1
    assert ("# Undercut\n\nArguments something undercuts.\n\n`" + UNDERCUT
            + "` · 3 matches\n\n- [CLAIM-001]") in text


def test_an_empty_outline_says_so(tmp_path, monkeypatch):
    root = project(tmp_path, monkeypatch, dialectic())
    doc(root, "CLAIM-001", "Alone")
    text = page(root)
    assert text.endswith("No matches.\n") and "- [" not in text
    assert "· 0 matches" in text


def test_facet_by_names_what_each_step_shows(tmp_path, monkeypatch):
    """`role` is a CLAIM field: claims show it, an argument omits it."""
    root = project(tmp_path, monkeypatch,
                   dialectic(undercut={"facet_by": ["status", "role"]}))
    record(root)
    lines = outline(page(root))
    assert lines[0].endswith("Thesis A *(Active, thesis)*")
    assert lines[1].endswith("Undercut twice *(Active)*")
    assert lines[2].endswith("Undercutter one *(Active, objection)*")


def test_a_scalar_facet_by_reads_as_a_list(tmp_path, monkeypatch):
    project(tmp_path, monkeypatch, dialectic(bare={"facet_by": "role"}))
    p = config.current().patterns
    assert p["bare"].facet_by == ("role",)
    assert p["undercut"].facet_by == ("status",)


def test_a_step_with_no_facet_value_shows_none(tmp_path, monkeypatch):
    root = project(tmp_path, monkeypatch,
                   dialectic(bare={"facet_by": ["role"]}))
    record(root)
    assert outline(page(root))[1] == (
        f"  - [ARG-001]({A}ARG-001.md) — Undercut twice")


@pytest.mark.parametrize("extra, says", [
    (dialectic(bare={"facet_by": ["weight"]}),
     "patterns.bare: `facet_by` names 'weight', which neither CLAIM nor ARG "
     "declares, so every step would render it blank (nameable: "),
    ({"patterns": {"p": {"match": "(g:ARG)", "output": "docs/p.md",
                         "facet_by": "role"}}},
     "patterns.p: `facet_by` names 'role', which ARG does not declare, so "
     "every step would render it blank (nameable: concludes, status)"),
    ({"patterns": {"p": {"match": "(g:ARG)", "facet_by": "status"}}},
     "patterns.p: `facet_by` annotates a page's steps, and there is no "
     "`output`"),
    ({"patterns": {"p": {"match": "(g:ARG)", "layout": "table"}}},
     "patterns.p: `layout` arranges a page, and there is no `output`"),
    ({"patterns": {"p": {"match": "(g:ARG)", "output": "docs/p.md",
                         "layout": "tree"}}},
     "patterns.p: `layout` is 'tree' — it is `outline` (the default) or "
     "`table`"),
    ({"patterns": {"p": {"match": "(g:ARG)", "output": "docs/p.md",
                         "layout": "table", "facet_by": "status"}}},
     "patterns.p: `facet_by` annotates an outline's steps, and a "
     "`layout: table` page has none"),
    (dialectic(undercut={"layout": "table"}),
     "patterns.undercut: `layout` is table, and patterns.bare renders to "
     f"{OUT} as an outline — patterns sharing an output share one page"),
    (dialectic(bare={"title": "One"}, undercut={"title": "Two"}),
     "patterns.undercut: `title` is 'Two', and patterns.bare gives "
     f"{OUT} the title 'One' — set it on one of them"),
    (dialectic(bare={"blurb": "One"}, undercut={"blurb": "Two"}),
     "patterns.undercut: `blurb` is 'Two', and patterns.bare gives "
     f"{OUT} the blurb 'One' — set it on one of them"),
    (dialectic(bare={"facet_by": "role"}, undercut={"facet_by": "status"}),
     "patterns.undercut: `facet_by` is ['status'], and patterns.bare gives "
     f"{OUT} the facet_by ['role'] — set it on one of them"),
])
def test_a_page_that_cannot_mean_what_it_says_is_refused(
        tmp_path, monkeypatch, extra, says):
    project(tmp_path, monkeypatch, extra)
    with pytest.raises(ValueError) as caught:
        config.load(tmp_path)
    assert str(caught.value).startswith(f"luria.yaml: {says}"), caught.value


def test_a_title_or_blurb_set_once_heads_the_shared_page(tmp_path, monkeypatch):
    """Set on either pattern; the same value on both agrees."""
    root = project(tmp_path, monkeypatch, dialectic(
        undercut={"title": "Dialectic", "blurb": "Every argument."},
        bare={"blurb": "Every argument."}))
    record(root)
    text = page(root)
    assert "# Dialectic\n\nEvery argument.\n" in text


def test_a_shared_output_still_collides_with_any_other_renderer(
        tmp_path, monkeypatch):
    project(tmp_path, monkeypatch, dialectic(), {"views": {"v": {
        "template": "t.j2", "output": OUT}}})
    with pytest.raises(ValueError) as caught:
        config.load(tmp_path)
    assert str(caught.value) == (
        f"luria.yaml: patterns.bare: `output` {OUT} is already where "
        "views.v renders")


def test_a_shared_output_is_one_view(tmp_path, monkeypatch):
    project(tmp_path, monkeypatch, dialectic())
    found = config.current().views
    assert list(found) == ["patterns.bare"]
    assert found["patterns.bare"].where == "patterns.bare and patterns.undercut"


def test_patterns_merge_by_position_not_by_name(tmp_path, monkeypatch):
    """The second node is the second column, whatever each pattern calls it."""
    root = project(tmp_path, monkeypatch, {"patterns": {
        "bare": {"match": BARE, "output": OUT},
        "undercut": {"match": "(x:CLAIM)<-[:concludes]-(y:ARG)"
                              "<-[:undercuts]-(z:CLAIM)", "output": OUT}}})
    record(root)
    lines = outline(page(root))
    assert len(lines) == 8 and lines[1].startswith("  - [ARG-001](")


def test_layout_table_is_the_flat_table(tmp_path, monkeypatch):
    root = project(tmp_path, monkeypatch, {"patterns": {"undercut": {
        "match": UNDERCUT, "output": OUT, "layout": "table"}}})
    record(root)
    text = page(root)
    assert f"`{UNDERCUT}` · 3 matches\n\n| c (CLAIM) | g (ARG) | u (CLAIM) |\n" \
           "|---|---|---|\n" in text
    assert "- [" not in text
    assert (f"| [CLAIM-002]({C}CLAIM-002.md) — Thesis B | [ARG-003]({A}ARG-003"
            f".md) — Undercut once | [CLAIM-004]({C}CLAIM-004.md) — "
            "Undercutter two |") in text


def test_tables_sharing_an_output_are_one_page_of_tables(
        tmp_path, monkeypatch):
    """Rows do not nest, so each pattern keeps its own table and columns."""
    root = project(tmp_path, monkeypatch, dialectic(
        bare={"layout": "table"}, undercut={"layout": "table"}))
    record(root)
    text = page(root)
    assert (f"**bare** · `{BARE}` · 3 matches\n\n| c (CLAIM) | g (ARG) |\n"
            in text)
    assert (f"Undercut once |\n\n**undercut** · `{UNDERCUT}` · 3 "
            "matches\n\n| c (CLAIM) | g (ARG) | u (CLAIM) |\n") in text
    assert text.endswith("Undercutter two |\n")


