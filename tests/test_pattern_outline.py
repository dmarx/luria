GOLDEN = """\
<!-- GENERATED by `luria index` — do not edit. -->

# Lines of work

2 lines, walked from `extends:` on LIT documents. Each step explains itself; this page is the order they came in.

## From The trunk

- [LIT-001](../record/literature.d/LIT-001.md) — The trunk *(Active, contested)*
  - [LIT-002](../record/literature.d/LIT-002.md) — Left *(Active, converged)*
    - [LIT-004](../record/literature.d/LIT-004.md) — Join *(Active, unassessed)* — also extends LIT-003
      - [LIT-006](../record/literature.d/LIT-006.md) — Later *(Proposed, unassessed)*
  - [LIT-003](../record/literature.d/LIT-003.md) — Right *(Active, unassessed)*
- alongside: [LIT-005](../record/literature.d/LIT-005.md) — Rival *(Active, unassessed)*

## From Other root

- [LIT-007](../record/literature.d/LIT-007.md) — Other root *(Active, unassessed)*
  - [LIT-008](../record/literature.d/LIT-008.md) — Other step *(Active, unassessed)*
"""


def test_a_chain_page_is_byte_identical_through_the_shared_renderer(
        tmp_path, monkeypatch):
    """Captured from `main` before the step renderer moved out of chains."""
    from test_chains import RELATIONS, SHOWN, VOCAB, _note
    from test_chains import project as chain_project
    root = chain_project(tmp_path, monkeypatch, merged(RELATIONS, VOCAB, SHOWN))
    config.reset()
    _note(root, 1, "The trunk", consensus="contested")
    _note(root, 2, "Left", extends=["LIT-001"], consensus="converged")
    _note(root, 3, "Right", extends=["LIT-001"])
    _note(root, 4, "Join", extends=["LIT-002", "LIT-003"])
    _note(root, 5, "Rival", compared_against=["LIT-001"])
    _note(root, 6, "Later", status="Proposed", extends=["LIT-004"])
    _note(root, 7, "Other root")
    _note(root, 8, "Other step", extends=["LIT-007"])
    assert chains.outputs()[root / "docs/lineage.md"] == GOLDEN


def test_a_step_reads_the_same_on_a_chain_and_an_outline(
        tmp_path, monkeypatch):
    """One renderer: the same document, rendered into the same directory."""
    from luria import steps
    from luria.adr_index import load_scheme
    root = project(tmp_path, monkeypatch, dialectic())
    record(root)
    cfg = config.current()
    arg = next(d for d in load_scheme(cfg.schemes["ARG"])
               if d.code == "ARG-001")
    shown = steps.step(arg, root / "docs", ("status",))
    assert shown in outline(page(root))[1]
    assert os.path.basename(steps.link(arg, root / "docs")) == "ARG-001.md"
