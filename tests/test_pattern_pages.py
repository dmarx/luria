# tests/test_pattern_pages.py
"""A named path pattern rendered as a page of its matches (#373).

A chain shows a pattern only as steps inside its lines, and only a pattern
that runs from its scheme back to it. Everything else a record wants to ask —
a claim nothing objects to, an argument something undercuts, a step the
record calls unfinished — is a list of matches, and this is that list.
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

from _config import merged
from luria import adr_index, config, pattern_report, pattern_rules, views
from luria.adr_index import outputs
from luria.view_document import _Refused

BASE = """
issue_url: https://example.test/issues/{n}
schemes:
  CLAIM:
    dir: record/claims.d
    output: docs/claims
    references:
      premise_of: {scheme: INF, many: true, required: false, converse: premises}
      objects_to: {scheme: CLAIM, many: true, required: false}
  INF:
    dir: record/inferences.d
    output: docs/inferences
    references:
      premises: {scheme: CLAIM, many: true, required: false, converse: premise_of}
      concludes: {scheme: CLAIM, required: false}
"""

UNFINISHED = {"patterns": {"unfinished": {
    "match": "(i:INF)<-[:premise_of]-(p:CLAIM) "
             "WHERE NOT (i)-[:concludes]->(:CLAIM)",
    "blurb": "Inferences with premises and no conclusion yet.",
    "output": "docs/unfinished.md",
    "title": "Unfinished steps"}}}


def project(tmp_path: Path, monkeypatch, *extra) -> Path:
    (tmp_path / "luria.yaml").write_text(merged(BASE, *extra))
    monkeypatch.setenv("LURIA_ROOT", str(tmp_path))
    config.reset()
    return tmp_path


def doc(root: Path, scheme: str, number: int, title: str, **fields) -> None:
    code = f"{scheme}-{number:03d}"
    folder = {"CLAIM": "claims.d", "INF": "inferences.d"}[scheme]
    front = ["---", "status: Active", f"title: {title!r}", "date: '2026-01-01'"]
    for key, value in fields.items():
        if isinstance(value, (list, tuple)):
            front.append(f"{key}:")
            front += [f"- {v}" for v in value]
        else:
            front.append(f"{key}: {value}")
    front += ["---", "", f"# {code}: {title}", "", "Body."]
    path = root / "record" / folder / f"{code}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(front) + "\n")


def argument(root: Path) -> None:
    doc(root, "CLAIM", 1, "First premise", premise_of=["INF-001", "INF-002"])
    doc(root, "CLAIM", 2, "Second premise", premise_of=["INF-002"])
    doc(root, "CLAIM", 3, "Conclusion")
    doc(root, "INF", 1, "Finished", concludes="CLAIM-003")
    doc(root, "INF", 2, "Unfinished | with a pipe")


def page(root: Path) -> str:
    return views.outputs()[root / "docs/unfinished.md"]


def test_a_page_lists_each_match_with_a_column_per_named_node(
        tmp_path, monkeypatch):
    root = project(tmp_path, monkeypatch, UNFINISHED)
    argument(root)
    text = page(root)
    assert text.startswith("<!-- GENERATED by `luria index`")
    assert "# Unfinished steps" in text
    assert "Inferences with premises and no conclusion yet." in text
    assert ("`(i:INF)<-[:premise_of]-(p:CLAIM) WHERE NOT "
            "(i)-[:concludes]->(:CLAIM)` · 2 matches") in text
    assert "| i (INF) | p (CLAIM) |\n|---|---|\n" in text
    rows = [line for line in text.splitlines() if line.startswith("| [")]
    assert rows == [
        "| [INF-002](../record/inferences.d/INF-002.md) — Unfinished \\| with "
        "a pipe | [CLAIM-001](../record/claims.d/CLAIM-001.md) — First premise |",
        "| [INF-002](../record/inferences.d/INF-002.md) — Unfinished \\| with "
        "a pipe | [CLAIM-002](../record/claims.d/CLAIM-002.md) — Second premise |",
    ]


def test_an_empty_result_says_so(tmp_path, monkeypatch):
    root = project(tmp_path, monkeypatch, UNFINISHED)
    doc(root, "CLAIM", 1, "Premise", premise_of=["INF-001"])
    doc(root, "CLAIM", 2, "Conclusion")
    doc(root, "INF", 1, "Finished", concludes="CLAIM-002")
    text = page(root)
    assert "· 0 matches" in text
    assert "No matches." in text
    assert "|---|" not in text


def test_a_zero_hop_pattern_renders(tmp_path, monkeypatch):
    root = project(tmp_path, monkeypatch, {"patterns": {"unopposed": {
        "match": "(c:CLAIM) WHERE NOT (c)<-[:objects_to]-(:CLAIM)",
        "output": "docs/unopposed.md"}}})
    doc(root, "CLAIM", 1, "Thesis")
    doc(root, "CLAIM", 2, "Objection", objects_to=["CLAIM-001"])
    text = views.outputs()[root / "docs/unopposed.md"]
    assert "# Unopposed" in text
    assert "· 1 match\n" in text
    assert "| [CLAIM-002](../record/claims.d/CLAIM-002.md) — Objection |" in text
    assert "CLAIM-001](" not in text


def test_anonymous_and_repeated_nodes_are_not_columns(tmp_path, monkeypatch):
    root = project(tmp_path, monkeypatch, {"patterns": {"steps": {
        "match": "(c:CLAIM)<-[:concludes]-(:INF)<-[:premise_of]-(p:CLAIM)",
        "output": "docs/steps.md"}}})
    argument(root)
    text = views.outputs()[root / "docs/steps.md"]
    assert "| c (CLAIM) | p (CLAIM) |" in text
    assert "INF-001" not in text


def test_matches_differing_only_in_an_anonymous_node_are_one_row(
        tmp_path, monkeypatch):
    """INF-002 has two premises; with the premise anonymous, nothing on a
    row tells the two matches apart, so the page lists INF-002 once."""
    root = project(tmp_path, monkeypatch, {"patterns": {"open": {
        "match": "(i:INF)<-[:premise_of]-(:CLAIM) "
                 "WHERE NOT (i)-[:concludes]->(:CLAIM)",
        "output": "docs/open.md"}}})
    argument(root)
    text = views.outputs()[root / "docs/open.md"]
    assert "· 1 match\n" in text
    assert text.count("| [INF-002](") == 1


def test_a_pattern_without_output_renders_nothing(tmp_path, monkeypatch):
    root = project(tmp_path, monkeypatch, {"patterns": {
        "quiet": "(c:CLAIM) WHERE NOT (c)<-[:objects_to]-(:CLAIM)"}})
    doc(root, "CLAIM", 1, "Alone")
    assert views.outputs() == {}


def test_the_page_is_a_view_luria_index_writes(tmp_path, monkeypatch):
    root = project(tmp_path, monkeypatch, UNFINISHED)
    argument(root)
    assert root / "docs/unfinished.md" in outputs()


def test_the_page_is_not_scanned_for_citations(tmp_path, monkeypatch):
    """A report lists retired documents as readily as live ones; scanned, it
    would fill the reference report with citations nobody can annotate."""
    root = project(tmp_path, monkeypatch, UNFINISHED)
    argument(root)
    assert config.current().is_generated(root / "docs/unfinished.md")


@pytest.mark.parametrize("extra, says", [
    ({"patterns": {"p": {"match": "(:CLAIM) WHERE NOT (:INF)",
                         "output": "docs/p.md"}}},
     "patterns.p: names no node"),
    ({"patterns": {"p": {"match": "(c:CLAIM)", "title": "No page"}}},
     "patterns.p: `title` names a page, and there is no `output`"),
])
def test_a_page_that_cannot_render_is_refused(tmp_path, monkeypatch, extra,
                                              says):
    project(tmp_path, monkeypatch, extra)
    with pytest.raises(ValueError, match=r"luria\.yaml: ") as caught:
        config.load(tmp_path)
    assert says in str(caught.value)


# One check covers every renderer whose path the config chooses, so each
# pairing that can occur is refused the same way, naming both.
P = {"match": "(c:CLAIM)"}
CHAIN = {"scheme": "CLAIM", "relation": "objects_to"}
VIEW = {"template": "record/views.d/v.md.j2"}


@pytest.mark.parametrize("extra, later, earlier", [
    # a pattern page against each other renderer
    ({"patterns": {"p": {**P, "output": "docs/claims"}}},
     "patterns.p", "schemes.CLAIM"),
    ({"patterns": {"p": {**P, "output": "docs/claims/README.md"}}},
     "patterns.p", "schemes.CLAIM"),
    ({"patterns": {"p": {**P, "output": "docs/x.md"},
                   "q": {**P, "output": "docs/x.md"}}},
     "patterns.q", "patterns.p"),
    ({"patterns": {"p": {**P, "output": "docs/reports/unbound-lineage.md"}}},
     "patterns.p", "the status report unbound-lineage.md"),
    ({"patterns": {"p": {**P, "output": "docs/x.md"}},
      "chains": {"c": {**CHAIN, "output": "docs/x.md"}}},
     "patterns.p", "chains.c"),
    ({"patterns": {"p": {**P, "output": "docs/x.md"}},
      "views": {"v": {**VIEW, "output": "docs/x.md"}}},
     "patterns.p", "views.v"),
    ({"patterns": {"p": {**P, "output": "docs/record.md"}}},
     "patterns.p", "the record description"),
    ({"patterns": {"p": {**P, "output": "docs/./x.md"},
                   "q": {**P, "output": "docs/x.md"}}},
     "patterns.q", "patterns.p"),
    # the pairings no check covered before (#373)
    ({"chains": {"c": {**CHAIN, "output": "docs/claims/README.md"}}},
     "chains.c", "schemes.CLAIM"),
    ({"views": {"v": {**VIEW, "output": "docs/inferences/README.md"}}},
     "views.v", "schemes.INF"),
    ({"schemes": {"NOTE": {"dir": "record/notes.d",
                           "output": "docs/claims"}}},
     "schemes.NOTE", "schemes.CLAIM"),
    ({"chains": {"c": {**CHAIN, "output": "docs/x.md"},
                 "d": {**CHAIN, "output": "docs/x.md"}}},
     "chains.d", "chains.c"),
    ({"chains": {"c": {**CHAIN, "output": "docs/reports/pending-decisions.md"}}},
     "chains.c", "the status report pending-decisions.md"),
    ({"chains": {"c": {**CHAIN, "output": "docs/x.md"}},
      "views": {"v": {**VIEW, "output": "docs/x.md"}}},
     "views.v", "chains.c"),
    ({"views": {"v": {**VIEW, "output": "docs/x.md"},
                "w": {"template": "record/views.d/w.md.j2",
                      "output": "docs/x.md"}}},
     "views.w", "views.v"),
    ({"views": {"v": {**VIEW, "output": "docs/reports/reference-status.md"}}},
     "views.v", "the status report reference-status.md"),
])
def test_two_renderers_at_one_path_are_refused(tmp_path, monkeypatch, extra,
                                               later, earlier):
    project(tmp_path, monkeypatch, extra)
    with pytest.raises(ValueError) as caught:
        config.load(tmp_path)
    said = str(caught.value)
    assert said.startswith(f"luria.yaml: {later}: `output` "), said
    assert f"is already where {earlier} renders" in said


def test_distinct_outputs_load(tmp_path, monkeypatch):
    """The control: the same renderers at different paths are no collision."""
    project(tmp_path, monkeypatch, {
        "patterns": {"p": {**P, "output": "docs/p.md"}},
        "chains": {"c": {**CHAIN, "output": "docs/c.md"}},
        "views": {"v": {**VIEW, "output": "docs/v.md"}}})
    cfg = config.load(tmp_path)
    assert {v.output for v in cfg.views.values()} == {
        tmp_path / "docs/p.md", tmp_path / "docs/v.md"}


# ── the page is a view: what the view machinery gives it ──────────────────

def test_index_check_holds_the_page_fresh(tmp_path, monkeypatch):
    root = project(tmp_path, monkeypatch, UNFINISHED)
    argument(root)
    adr_index.run()
    assert "INF-002" in (root / "docs/unfinished.md").read_text()
    assert root / "docs/unfinished.md" not in adr_index.staleness().stale
    doc(root, "INF", 3, "Another unfinished step")
    doc(root, "CLAIM", 4, "Its premise", premise_of=["INF-003"])
    assert root / "docs/unfinished.md" in adr_index.staleness().stale


def test_a_render_error_names_the_pattern_and_the_template_line(
        tmp_path, monkeypatch):
    root = project(tmp_path, monkeypatch, UNFINISHED)
    argument(root)

    def refused(self, pattern):
        raise _Refused("the solver is out to lunch")
    monkeypatch.setattr(views._Record, "match", refused)
    found = views.errors()
    assert len(found) == 1
    assert re.fullmatch(r"patterns\.unfinished: luria:pattern\.md\.j2:\d+: "
                        r"the solver is out to lunch", found[0]), found


def test_the_stamp_names_the_pattern_not_a_template_to_edit(
        tmp_path, monkeypatch):
    root = project(tmp_path, monkeypatch, UNFINISHED)
    argument(root)
    assert page(root).splitlines()[0] == (
        "<!-- GENERATED by `luria index` from patterns.unfinished in "
        "luria.yaml — edit that, not this file. -->")


# ── a page and a lint class over one pattern (#382) ───────────────────────

BOTH = {"patterns": {"unfinished": {**UNFINISHED["patterns"]["unfinished"],
                                    "report": True}}}


def test_a_pattern_may_have_a_page_and_a_class_and_they_agree(
        tmp_path, monkeypatch):
    root = project(tmp_path, monkeypatch, BOTH)
    argument(root)
    lint_rows = pattern_rules.reported()["unfinished"]
    page_rows = [(row["i"].code, row["p"].code) for row in
                 views._Record(root / "docs/unfinished.md").match("unfinished")]
    assert lint_rows == page_rows == [("INF-002", "CLAIM-001"),
                                      ("INF-002", "CLAIM-002")]
    assert "· 2 matches" in page(root)


def test_an_acknowledged_match_is_still_on_the_page(tmp_path, monkeypatch):
    """The page is a list; `pattern-ok:` silences the finding, not the row."""
    root = project(tmp_path, monkeypatch, BOTH)
    argument(root)
    path = root / "record/inferences.d/INF-002.md"
    path.write_text(path.read_text() + "\n<!-- pattern-ok: unfinished — "
                    "waiting on the survey -->\n")
    found = pattern_report.findings()
    assert "unfinished" not in found.rows and found.acknowledged == 2
    text = page(root)
    assert "· 2 matches" in text
    assert text.count("| [INF-002](") == 2
